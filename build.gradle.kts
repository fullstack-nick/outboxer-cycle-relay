tasks.register("licenseReport") {
    group = "verification"
    description = "Writes a deterministic inventory of resolved JVM dependencies and runtime images."
    dependsOn(subprojects.map { "${it.path}:dependencyInventory" })
    doLast {
        val dependencies = fileTree(layout.buildDirectory.dir("reports/licenses/components"))
            .matching { include("*.txt") }
            .files
            .flatMap { it.readLines(StandardCharsets.UTF_8) }
            .filter(String::isNotBlank)
            .toSortedSet()

        val output = layout.buildDirectory.file("reports/licenses/resolved-dependencies.txt").get().asFile
        output.parentFile.mkdirs()
        val lines = buildList {
            add("Outboxer resolved dependency inventory")
            add("Generated by: ./gradlew licenseReport")
            add("")
            add("JVM modules")
            addAll(dependencies)
            add("")
            add("Runtime container images")
            add("apache/kafka:4.3.1")
            add("eclipse-mosquitto:2.1.2-alpine")
            add("eclipse-temurin:21-jdk-jammy@sha256:ce5767b7222312d42395f5bab033cd91f09e44032a2f21bdfd7b5b912dbe1e77")
            add("eclipse-temurin:21-jre-jammy@sha256:eebd356ad7358b7094758e5787a6726f332917cfd56feab6457c56dab895cdbf")
            add("postgres:18.6-alpine")
        }
        output.writeText(lines.joinToString(System.lineSeparator(), postfix = System.lineSeparator()), StandardCharsets.UTF_8)
        logger.lifecycle("Dependency inventory written to ${output.relativeTo(rootDir)}")
    }
}

fun localScript(powerShellScript: String, bashScript: String, vararg arguments: String): List<String> {
    val windows = System.getProperty("os.name").startsWith("Windows")
    return if (windows) {
        listOf("pwsh", "-NoProfile", "-File", powerShellScript) + arguments
    } else {
        listOf("bash", bashScript) + arguments
    }
}

