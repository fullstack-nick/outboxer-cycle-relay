plugins {
    base
    alias(libs.plugins.spring.boot) apply false
    alias(libs.plugins.kotlin.jvm) apply false
    alias(libs.plugins.kotlin.spring) apply false
    alias(libs.plugins.spotless)
}

group = "io.github.fullstacknick.outboxer"
version = "1.0.0"

allprojects {
    group = rootProject.group
    version = rootProject.version
}

subprojects {
    val moduleName = name
    val internalGroup = rootProject.group.toString()
    val inventoryOutput = rootProject.layout.buildDirectory.file("reports/licenses/components/$moduleName.txt")

    configurations.configureEach {
        resolutionStrategy.activateDependencyLocking()
    }

    tasks.withType<Test>().configureEach {
        useJUnitPlatform()
        testLogging {
            events("failed", "skipped")
        }
    }

    tasks.register("dependencyInventory") {
        group = "verification"
        description = "Resolves this module's dependency coordinates for the root license report."
        doLast {
            val dependencies = sortedSetOf<String>()
            listOf("runtimeClasspath", "testRuntimeClasspath", "integrationTestRuntimeClasspath")
                .mapNotNull(configurations::findByName)
                .filter { it.isCanBeResolved }
                .forEach { configuration ->
                    configuration.incoming.resolutionResult.allComponents.forEach { component ->
                        component.moduleVersion
                            ?.takeUnless { module -> module.group == internalGroup }
                            ?.let { module -> dependencies += "${module.group}:${module.name}:${module.version}" }
                    }
                }
            val output = inventoryOutput.get().asFile
            output.parentFile.mkdirs()
            output.writeText(
                dependencies.joinToString(System.lineSeparator(), postfix = System.lineSeparator()),
                StandardCharsets.UTF_8,
            )
        }
    }
}

